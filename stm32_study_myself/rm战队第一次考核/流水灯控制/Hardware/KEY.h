/**
 ******************************************************************************
 * @file    KEY.h
 * @brief   板载按键（PA0）—— 每按一次切换一种灯效
 * @note    这里不用 EXTI 中断，用"定时轮询"：主循环每 20ms 调一次 KEY_Scan()
 ******************************************************************************
 */
#ifndef __KEY_H
#define __KEY_H

#include "stm32f10x.h"

void    KEY_Init(void);     /* 配 PA0 为上拉输入（GPIO 输入外设） */
uint8_t KEY_Scan(void);     /* 非阻塞扫描：返回 1 = 有一次可靠的"按下"，0 = 没事件 */

#endif /* __KEY_H */
